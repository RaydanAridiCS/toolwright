export type Tier = "low" | "medium" | "high" | "very-high";
export type Cluster = "pdf" | "image" | "dev" | "data" | "text" | "calc" | "design" | "gen" | "enc";

export interface KeywordEntry {
  /** The one query this page owns (equals the tool's primaryKeyword). */
  primary: string;
  /** Searcher intent: "do" wants the job done now, "learn" wants an explanation, "look-up" wants a reference value. */
  intent: Intent;
  /** ESTIMATE of search demand. */
  volume: Tier;
  /** ESTIMATE of how hard the first page is to reach, given who ranks. */
  difficulty: Tier;
  /** What the results for this kind of query usually look like (see SERP_CLUSTERS). */
  serp: Cluster;
  /** 5 to 15 related queries and synonyms the page should cover naturally. */
  secondary: string[];
  /** Modifiers that fit this tool and that we can say truthfully. */
  modifiers: string[];
  /** What we can say better than the usual result. */
  edge: string;
}

