#!/usr/bin/env node
/**
 * Generates docs/keyword-map.md from packages/tools/src/seo/keyword-map.ts and each tool's meta.ts.
 * Run with `npm run docs:seo`. `--check` fails if the committed file is out of date.
 * Node 22.18+ reads the TypeScript data file directly (it only uses erasable syntax).
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const toolsDir = join(root, "packages/tools/src/tools");
const out = join(root, "docs/keyword-map.md");
const { KEYWORD_MAP, SERP_CLUSTERS } = await import(pathToFileURL(join(root, "packages/tools/src/seo/keyword-map.ts")).href);

const field = (source, key) => {
  const m = new RegExp(`${key}:\\s*"((?:[^"\\\\]|\\\\.)*)"`).exec(source) ?? new RegExp(`${key}:\\s*\\n\\s*"((?:[^"\\\\]|\\\\.)*)"`).exec(source);
  return m ? m[1].replace(/\\"/g, '"').replace(/\\\\/g, "\\") : "";
};
const categoriesSource = readFileSync(join(root, "packages/tools/src/categories.ts"), "utf8");
const categories = [...categoriesSource.matchAll(/\{ id: "([a-z]+)", name: "([^"]+)"/g)].map((m) => ({ id: m[1], name: m[2] }));

const tools = readdirSync(toolsDir)
  .filter((d) => existsSync(join(toolsDir, d, "meta.ts")))
  .sort()
  .map((slug) => {
    const source = readFileSync(join(toolsDir, slug, "meta.ts"), "utf8");
    return { slug, name: field(source, "name"), category: field(source, "category"), title: field(source, "seoTitle") };
  });

const cell = (s) => String(s).replace(/\|/g, "/");
const lines = [
  "# Keyword and intent map",
  "",
  `One primary query per page, for all ${tools.length} tools. **None of the volume, difficulty or SERP notes is measured**: they are estimates from general knowledge, written without a keyword-research tool. Use them to order work, then replace them with real queries from Search Console and Bing Webmaster Tools.`,
  "",
  "> Generated by `npm run docs:seo` from `packages/tools/src/seo/keyword-map.ts`. Do not edit this file by hand; edit the data file and run the script.",
  "",
  "## What the results usually look like",
  "",
  "| Kind of tool | What the top results usually offer (unverified) |",
  "| --- | --- |",
  ...Object.entries(SERP_CLUSTERS).map(([k, v]) => `| ${k} | ${cell(v)} |`),
  "",
  "Our angle on every page is the same, and it is true: your files never leave your device, there is no sign-up, no watermark, and nothing to pay for.",
  "",
];
for (const c of categories) {
  const list = tools.filter((t) => t.category === c.id);
  if (!list.length) continue;
  lines.push(`## ${c.name} (${list.length})`, "");
  lines.push("| Tool | Primary query | Intent | Volume (est.) | Difficulty (est.) | Secondary queries | Modifiers | What we say better |", "| --- | --- | --- | --- | --- | --- | --- | --- |");
  for (const t of list) {
    const e = KEYWORD_MAP[t.slug];
    lines.push(`| [${cell(t.name)}](../packages/tools/src/tools/${t.slug}) | **${cell(e.primary)}** | ${e.intent} | ${e.volume} | ${e.difficulty} | ${cell(e.secondary.join(", "))} | ${cell(e.modifiers.join(", "))} | ${cell(e.edge)} |`);
  }
  lines.push("");
}
const content = lines.join("\n").replace(/ +\|/g, " |");

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== content) {
    console.error("docs/keyword-map.md is out of date. Run `npm run docs:seo`.");
    process.exit(1);
  }
} else {
  writeFileSync(out, content);
  console.log(`docs/keyword-map.md: ${tools.length} tools`);
}
